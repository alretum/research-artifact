#!/usr/bin/env python3
"""Build this repo's competency manifests and corpus tree from a paper-al-quiz-generation checkout.

Reads the upstream catalogues (<paper>/competencies/<COURSE>.json) and the hand-authored mapping
(config/competency-mapping.yml), and writes config/competencies/<COURSE>.yml. With --corpus it also
materialises corpus/<COURSE>/<deck folder>/<file>.pdf from <paper>/slides/<COURSE>/, and with --requests
it translates the built upstream requests into config/requests/paper2-<course>.yml.

Titles, taxonomy and descriptions are copied from the catalogue unchanged: they are the reference
values the benchmark scores each question against. Only `query` and `lectureUnits` come from the
mapping.
"""
import argparse
import json
import os
import re
import shutil
import sys

import yaml

COURSES = ('EIDI', 'PSE', 'EIST')


def slug(title):
    """Mirror CompetencyCatalogue.slug so keys match what the Java loader would derive."""
    out = re.sub(r'[^0-9A-Za-zÀ-ɏ]+', '-', title.lower())
    return out.strip('-')


def quote(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(course, catalogue, mapping):
    lines = [
        f'# Competency manifest for {course}. Generated by build-competency-maps.py -- do not edit.',
        '#',
        '# Titles, taxonomy and descriptions are the upstream catalogue verbatim; `query` and',
        '# `lectureUnits` come from config/competency-mapping.yml.',
        '',
        'course:',
        f'  key: {course}',
        f'  title: {quote(catalogue.get("name", course))}',
        f'  description: {quote("Language: " + mapping.get("language", "en"))}',
        '',
        'competencies:',
    ]
    decks = mapping.get('decks') or {}
    entries = mapping.get('competencies') or {}
    for competency in catalogue['competencies']:
        key = slug(competency['title'])
        entry = entries.get(key, {})
        lines.append('')
        lines.append(f'  - key: {key}')
        lines.append(f'    title: {quote(competency["title"])}')
        lines.append(f'    taxonomy: {competency["taxonomy"]}')
        if entry.get('query'):
            lines.append(f'    query: {quote(" ".join(entry["query"].split()))}')
        lines.append('    description: |-')
        for bullet in competency.get('description') or []:
            lines.append(f'      {bullet.strip()}')
        documents = entry.get('documents') or []
        if documents:
            lines.append('    lectureUnits:')
            for document in documents:
                lines.append(f'      - document: {quote(decks[document] + "/" + document)}')
    return '\n'.join(lines) + '\n'


def validate(course, catalogue, mapping, slides):
    problems = []
    keys = {slug(c['title']) for c in catalogue['competencies']}
    decks = mapping.get('decks') or {}
    for key, entry in (mapping.get('competencies') or {}).items():
        if key not in keys:
            problems.append(f'{course}: mapping key {key!r} matches no catalogue title')
        for document in entry.get('documents') or []:
            if document not in decks:
                problems.append(f'{course}: competency {key!r} links {document!r}, which is not in decks')
    if os.path.isdir(slides):
        present = {name for name in os.listdir(slides) if name.lower().endswith('.pdf')}
        for name in sorted(present - set(decks)):
            problems.append(f'{course}: deck {name!r} is in slides but has no folder name in decks')
        for name in sorted(set(decks) - present):
            problems.append(f'{course}: decks names {name!r}, which is not in {slides}')
    folders = {}
    for name, folder in decks.items():
        folders.setdefault(folder, []).append(name)
    for folder, names in sorted(folders.items()):
        if len(names) > 1:
            problems.append(f'{course}: folder {folder!r} is used by {len(names)} decks: {sorted(names)}')
    return problems


def materialise(course, mapping, slides, corpus):
    root = os.path.join(corpus, course)
    copied = 0
    for name, folder in sorted((mapping.get('decks') or {}).items()):
        source = os.path.join(slides, name)
        if not os.path.isfile(source):
            continue
        target = os.path.join(root, folder, name)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        if not os.path.exists(target) or os.path.getsize(target) != os.path.getsize(source):
            shutil.copy2(source, target)
        copied += 1
    return root, copied


TYPES = {'single_choice': 'single-choice', 'multiple_choice': 'multiple-choice', 'true_false': 'true-false'}


def requests(paper, out, per_competency, items):
    """Translate the upstream built requests into this repo's request-file shape, one file per course.

    `topic_title` is dropped: a request carries either a topic or competencies, never both.

    Two shapes are written per course. `paper2-<course>.yml` is the upstream design unchanged, three
    competencies per request. `paper2-<course>-per-competency.yml` splits each of those into one request
    per competency, keyed `<topic id>-<competency key>`, which makes every question's competency
    attribution unambiguous. The two shapes are not interchangeable: they differ in request count, in
    `source_material`, and in whether `objective_balance` has anything to measure.
    """
    source = os.path.join(paper, 'paper-generation', 'experiment', 'out', 'requests')
    grouped = {}
    split = {}
    for name in sorted(os.listdir(source)):
        if not name.endswith('.json'):
            continue
        request = json.load(open(os.path.join(source, name), encoding='utf-8'))
        course = request['course']
        types = ', '.join(TYPES[t] for t in request['question_types'])
        entry = [
            f'  course: {course}',
            f'  language: {request["language"]}',
            f'  question-types: [{types}]',
            f'  difficulty: {request["difficulty"]}',
        ]
        prompt = [f'  optional-prompt: {quote(request["instructor_prompt"])}'] if request.get('instructor_prompt') else []

        lines = grouped.setdefault(course, [])
        lines.append('')
        lines.append(f'- key: {request["request_id"]}')
        lines.append('  competencies: [' + ', '.join(slug(t) for t in request['competencies']) + ']')
        lines += entry + [f'  number-of-questions: {request["num_questions"]}'] + prompt

        lines = split.setdefault(course, [])
        for title in request['competencies']:
            lines.append('')
            lines.append(f'- key: {request["request_id"]}-{slug(title)}')
            lines.append(f'  competencies: [{slug(title)}]')
            lines += entry + [f'  number-of-questions: {items}'] + prompt

    os.makedirs(out, exist_ok=True)
    header = [
        '# Quiz requests generated by build-competency-maps.py from the upstream built requests.',
        '# Do not edit. Competency keys are the slug of the upstream competency title.',
    ]
    for suffix, written in (('', grouped), ('-per-competency', split)):
        if suffix and not per_competency:
            continue
        for course, lines in sorted(written.items()):
            target = os.path.join(out, f'paper2-{course.lower()}{suffix}.yml')
            open(target, 'w', encoding='utf-8').write('\n'.join(header + lines) + '\n')
            print(f'{target}: {sum(1 for line in lines if line.startswith("- key:"))} requests')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--paper', required=True, help='path to a paper-al-quiz-generation checkout')
    parser.add_argument('--mapping', default='config/competency-mapping.yml')
    parser.add_argument('--out', default='config/competencies')
    parser.add_argument('--corpus', default=None, help='also copy the decks into this corpus root')
    parser.add_argument('--requests', default=None, help='also write the translated request files here')
    parser.add_argument('--per-competency', action='store_true', help='also write one request per competency')
    parser.add_argument('--items', type=int, default=8, help='questions per per-competency request (default 8)')
    args = parser.parse_args()

    mappings = yaml.safe_load(open(args.mapping, encoding='utf-8'))
    os.makedirs(args.out, exist_ok=True)
    problems = []
    for course in COURSES:
        path = os.path.join(args.paper, 'competencies', f'{course}.json')
        catalogue = json.load(open(path, encoding='utf-8'))
        mapping = mappings.get(course) or {}
        slides = os.path.join(args.paper, 'slides', course)
        problems += validate(course, catalogue, mapping, slides)
        target = os.path.join(args.out, f'{course}.yml')
        open(target, 'w', encoding='utf-8').write(render(course, catalogue, mapping))
        linked = sum(1 for e in (mapping.get('competencies') or {}).values() if e.get('documents'))
        queried = sum(1 for e in (mapping.get('competencies') or {}).values() if e.get('query'))
        print(f'{target}: {len(catalogue["competencies"])} competencies, {queried} with a query, {linked} linked')
        if args.corpus:
            root, copied = materialise(course, mapping, slides, args.corpus)
            print(f'  {root}: {copied} decks')

    if args.requests:
        requests(args.paper, args.requests, args.per_competency, args.items)

    for problem in problems:
        print(f'PROBLEM {problem}', file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
